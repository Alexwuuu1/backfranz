def glyph(ch):
    if ch == ' ':
        return ['000'] * 10
    decomposition = unicodedata.normalize('NFD', ch)
    rows = patterns.get(decomposition[0],patterns['?']).split('/')
    if ch == '¿':
        rows = [row[::-1] for row in patterns['?'].split('/')[::-1]]
    if ch == '¡':
        rows = patterns['!'].split('/')[::-1]
    if len(decomposition)>1 and len(rows[0])<5:
        rows = [row.center(5,'0') for row in rows]
    width = len(rows[0])
    rows = ['0' * width for _ in range(3)] + rows
    if '\u0301' in decomposition:
        rows[0] = '00010'
        rows[1] = '00100'
    elif '\u0303' in decomposition:
        rows[0] = '01101'
        rows[1] = '01011'
    elif '\u0308' in decomposition:
        rows[1] = '01010'
    columns = [x for x in range(width) if any(row[x]=='1' for row in rows)]
    if not columns:
        return rows
    return [row[columns[0]:columns[-1]+1] for row in rows]
